UPDATE rutas route
SET id_agencia_origen = agency.id_agencia
FROM agencias agency
WHERE route.id_agencia_origen IS NULL
  AND agency.codigo = 'AYA';

UPDATE rutas route
SET id_agencia_destino = agency.id_agencia
FROM agencias agency
WHERE route.id_agencia_destino IS NULL
  AND (
    LOWER(agency.ciudad) = LOWER(TRIM(route.destino))
    OR LOWER(agency.nombre) = LOWER('Agencia ' || TRIM(route.destino))
  );

