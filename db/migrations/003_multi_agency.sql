CREATE TABLE IF NOT EXISTS agencias (
  id_agencia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL,
  ciudad VARCHAR(80) NOT NULL,
  direccion VARCHAR(180) NOT NULL,
  telefono VARCHAR(20),
  email VARCHAR(150),
  estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVA',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT agencias_codigo_check
    CHECK (codigo ~ '^[A-Z0-9-]{2,20}$'),
  CONSTRAINT agencias_estado_check
    CHECK (estado IN ('ACTIVA', 'INACTIVA')),
  CONSTRAINT agencias_telefono_check
    CHECK (telefono IS NULL OR telefono ~ '^[0-9+ -]{7,20}$'),
  CONSTRAINT agencias_email_check
    CHECK (email IS NULL OR email = LOWER(email))
);

CREATE UNIQUE INDEX IF NOT EXISTS agencias_nombre_ciudad_unique
  ON agencias (LOWER(nombre), LOWER(ciudad));

