CREATE TABLE IF NOT EXISTS usuarios_agencias (
  id_usuario INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
  id_agencia INTEGER NOT NULL REFERENCES agencias(id_agencia) ON DELETE RESTRICT,
  es_principal BOOLEAN NOT NULL DEFAULT FALSE,
  estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVO',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id_usuario, id_agencia),
  CONSTRAINT usuarios_agencias_estado_check
    CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE UNIQUE INDEX IF NOT EXISTS usuarios_agencias_principal_unique
  ON usuarios_agencias (id_usuario)
  WHERE es_principal = TRUE AND estado = 'ACTIVO';
CREATE INDEX IF NOT EXISTS usuarios_agencias_agencia_idx
  ON usuarios_agencias (id_agencia, estado);

